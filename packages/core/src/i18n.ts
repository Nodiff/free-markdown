const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  en,
}

export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string

export function createI18n(locale: Locale): Translator {
  const dict = dictionaries[locale] ?? zhCN
  return (key, vars) => {
    const template = dict[key] ?? zhCN[key] ?? key
    if (!vars) return template
    return template.replace(/\{(\w+)\}/g, (match, name: string) => {
      const value = vars[name]
      return value === undefined ? match : String(value)
    })
  }
}

/** 从 Electron 的 app.getLocale() 推断界面语言 */
export function localeFromSystem(raw: string): Locale {
  return raw.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

export function isLocale(value: unknown): value is Locale {
  return value === 'zh-CN' || value === 'en'
}
